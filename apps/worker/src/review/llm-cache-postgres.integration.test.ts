      expect(payload.reason).toBe('SQL injection confirmed in query concatenation');
      expect(payload.findings).toHaveLength(1);
      expect(payload.findings[0].severity).toBe('critical');
      expect(payload.findings[0].message).toContain('Direct interpolation');

      // 3. Lecture via le store
