    it('fonctionne de façon concurrente avec des écritures (set) sans blocage ni interférence', async () => {
      expect(isPostgresAvailable).toBe(true);

      const store = new DbLlmCacheStore(db);
      const prefix = `${TEST_KEY_PREFIX}concurrent-`;

      // Insérer d'abord 20 entrées expirées
      for (let i = 0; i < 20; i++) {
        const key = `${prefix}exp-${i}-${randomUUID()}`;
        await store.set(key, {
          decision: 'UNCERTAIN',
          reason: `Concurrent expired ${i}`,
          provider: 'p',
          model: 'm',
          tier: 1,
          tokensIn: 10,
          tokensOut: 5,
          createdAt: new Date().toISOString(),
        }, -1000);
      }

      // Lancer simultanément le nettoyage par lots ET l'écriture de 10 entrées valides
      const activeKeys: string[] = [];
      const concurrentWrites = Array.from({ length: 10 }, (_, i) => {
        const key = `${prefix}active-${i}-${randomUUID()}`;
        activeKeys.push(key);
        return store.set(key, {
          decision: 'CONFIRMED',
          reason: `Concurrent active entry ${i}`,
          provider: 'p',
          model: 'm',
          tier: 1,
          tokensIn: 100,
          tokensOut: 40,
          createdAt: new Date().toISOString(),
        }, 3600_000);
      });

      const cleanupPromise = store.cleanExpired({
        keyPrefix: prefix,
        batchSize: 5,
      });

      // Les deux opérations doivent se terminer sans deadlock ni échec
      const [cleanupResult, ...writeResults] = await Promise.all([cleanupPromise, ...concurrentWrites]);

      expect(cleanupResult).toBe(20);
      expect(writeResults).toHaveLength(10);

      // Vérifier que toutes les entrées actives sont intactes et lisibles
      for (const key of activeKeys) {
        const entry = await store.get(key);
        expect(entry).not.toBeNull();
        expect(entry?.decision).toBe('CONFIRMED');
      }

      // Vérifier que les 20 entrées expirées ont bien disparu
      const remainingExpired = await db
        .select()
        .from(llmCache)
        .where(like(llmCache.cacheKey, `${prefix}exp-%`));
      expect(remainingExpired.length).toBe(0);
    });

