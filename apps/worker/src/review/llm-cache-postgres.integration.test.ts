      expect(rowExp1).toBeUndefined();
      expect(rowExp2).toBeUndefined();
      expect(rowExp3).toBeUndefined();

      // Vérifier que les entrées valides et l'entrée permanente sont intactes
      const [rowValid1] = await db.select().from(llmCache).where(eq(llmCache.cacheKey, valid1));
      const [rowValid2] = await db.select().from(llmCache).where(eq(llmCache.cacheKey, valid2));
      const [rowNoExp] = await db.select().from(llmCache).where(eq(llmCache.cacheKey, noExpiryKey));
      expect(rowValid1).toBeDefined();
      expect(rowValid2).toBeDefined();
      expect(rowNoExp).toBeDefined();

      // Relecture via store pour confirmer la disponibilité
      const freshStore = new DbLlmCacheStore(db);
      const resValid1 = await freshStore.get(valid1);
      expect(resValid1?.reason).toBe('Valid 1');
