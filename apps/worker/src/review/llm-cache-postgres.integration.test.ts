const TEST_KEY_PREFIX = 'intg-test-cache-';

function makeTestKey(suffix = ''): string {
  return `${TEST_KEY_PREFIX}${suffix}-${randomUUID()}`;
}

function createMockLlm(
  name = 'mock-postgres-provider',
  model = 'mock-model-v1',
  onGenerate?: (prompt: string) => any,
): LlmProvider & { callCount: number } {
  let callCount = 0;
  return {
    name,
    model,
    get callCount() {
      return callCount;
    },
    async generate({ prompt }) {
      callCount++;
      if (onGenerate) {
        const res = onGenerate(prompt);
        return {
          text: typeof res === 'string' ? res : JSON.stringify(res.data ?? res),
          tokensIn: res.tokensIn ?? 120,
          tokensOut: res.tokensOut ?? 45,
        };
      }
      return {
        text: JSON.stringify({
          summary: 'Automated integration review summary',
          findings: [],
          semgrep_decisions: [],
        }),
        tokensIn: 120,
        tokensOut: 45,
      };
    },
  };
}

