      const [probe] = await db.select({ val: sql<number>`1` }).from(llmCache).limit(1);
      if (probe !== undefined || true) {
        isPostgresAvailable = true;
      }
      // Count pre-existing non-test rows to guarantee they are never touched
      const preExisting = await db
        .select({ key: llmCache.cacheKey })
        .from(llmCache)
        .where(sql`${llmCache.cacheKey} NOT LIKE ${TEST_KEY_PREFIX + '%'}`);
